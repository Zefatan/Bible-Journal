/**
 * One-time (well, occasional) data build: fetches the exact verse count for
 * every chapter of every book from api.bible — the same NIV source the app
 * reads from — and writes src/utils/verseCounts.js. Re-run this only if the
 * Bible source/translation ever changes.
 *
 * Usage: node scripts/build-verse-counts.mjs   (run from the project root)
 */
import fs from 'fs';
import { OT_BOOKS, NT_BOOKS, PSALMS } from '../src/utils/readingPlan.js';

const env = fs.readFileSync('.env', 'utf8');
const KEY = env.match(/VITE_BIBLE_API_KEY=(.+)/)[1].trim();
const BIBLE_ID = '78a9f6124f344018-01';
const ALL = [...OT_BOOKS, ...PSALMS.filter(p => !OT_BOOKS.some(b => b.id === p.id)), ...NT_BOOKS];

async function verseCount(bookId, chapter, attempt = 1) {
  const url = `https://rest.api.bible/v1/bibles/${BIBLE_ID}/chapters/${bookId}.${chapter}/verses`;
  const res = await fetch(url, { headers: { 'api-key': KEY } });
  if (!res.ok) {
    if (attempt < 3) { await sleep(500 * attempt); return verseCount(bookId, chapter, attempt + 1); }
    throw new Error(`${bookId}.${chapter} -> HTTP ${res.status}`);
  }
  const json = await res.json();
  return json.data.length;
}

function sleep(ms) { return new Promise(r => setTimeout(r, ms)); }

const result = {};
let totalVerses = 0;
let totalChapters = 0;

for (const book of ALL) {
  const counts = [];
  for (let ch = 1; ch <= book.chapters; ch++) {
    const n = await verseCount(book.id, ch);
    counts.push(n);
    totalVerses += n;
    totalChapters++;
    await sleep(80);
  }
  result[book.id] = counts;
  console.log(`${book.id.padEnd(4)} ${book.name.padEnd(16)} ${book.chapters} chapters, ${counts.reduce((a, b) => a + b, 0)} verses`);
}

console.log(`\nTOTAL: ${totalChapters} chapters, ${totalVerses} verses`);

const out = `/**
 * verseCounts.js — verses per chapter for every book, sourced directly from
 * the same NIV Bible (api.bible, bibleId ${BIBLE_ID}) the app already reads
 * from, so progress tracking matches exactly what a user sees when reading.
 * Generated by scripts/build-verse-counts.mjs — regenerate if the Bible
 * source ever changes. Total: ${totalChapters} chapters, ${totalVerses} verses.
 */
export const VERSE_COUNTS = ${JSON.stringify(result)};

/** Number of verses in a given book/chapter, or 0 if unknown. */
export function getChapterVerseCount(bookId, chapter) {
  return VERSE_COUNTS[bookId]?.[chapter - 1] || 0;
}

/** Total verses across an entire list of books (e.g. a reading stream). */
export function getBooksVerseTotal(books) {
  return books.reduce((sum, b) => sum + (VERSE_COUNTS[b.id]?.reduce((s, n) => s + n, 0) || 0), 0);
}
`;

fs.writeFileSync('src/utils/verseCounts.js', out);
console.log('\nWrote src/utils/verseCounts.js');
